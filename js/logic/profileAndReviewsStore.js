export function loadLocalProfileSettings(storageKey, defaultSettings) {
    try {
        const raw = localStorage.getItem(storageKey);
        if (raw) {
            return { ...defaultSettings, ...JSON.parse(raw) };
        }
    } catch {}
    return defaultSettings;
}

export function saveLocalProfileSettings(storageKey, settings) {
    try {
        localStorage.setItem(storageKey, JSON.stringify(settings));
    } catch {}
}

export async function loadCloudProfileSettings(db, defaultSettings) {
    try {
        const ref = db.collection("teacherProfile").doc("primary");
        const snap = await ref.get();
        if (snap.exists) {
            const data = snap.data() || {};
            return { ...defaultSettings, ...data };
        }
    } catch (e) {
        console.warn("Could not load cloud profile settings", e);
    }
    return defaultSettings;
}

export async function saveCloudProfileSettings(db, firebaseOrSettings, optionalSettings) {
    try {
        const ref = db.collection("teacherProfile").doc("primary");
        const settings = optionalSettings || firebaseOrSettings;
        const firebaseObj = optionalSettings ? firebaseOrSettings : null;
        await ref.set(
            {
                ...settings,
                updatedAt: firebaseObj?.firestore?.FieldValue?.serverTimestamp?.() || Date.now(),
            },
            { merge: true }
        );
    } catch (e) {
        console.error("Could not save cloud profile settings", e);
        throw e;
    }
}

export function loadLocalReviews(storageKey, defaultReviews) {
    try {
        const raw = localStorage.getItem(storageKey);
        if (raw) {
            const list = JSON.parse(raw);
            if (Array.isArray(list) && list.length > 0) return list;
        }
    } catch {}
    return defaultReviews;
}

export function saveLocalReviews(storageKey, reviews) {
    try {
        localStorage.setItem(storageKey, JSON.stringify(reviews));
    } catch {}
}

export async function loadCloudReviews(db, defaultReviews) {
    try {
        const snap = await db.collection("reviews")
            .limit(100)
            .get();
        if (!snap.empty) {
            const items = [];
            snap.forEach((doc) => {
                items.push({ id: doc.id, ...doc.data() });
            });
            items.sort((a, b) => (b.createdAt || 0) - (a.createdAt || 0));
            return items;
        }
    } catch (e) {
        console.warn("Could not load cloud reviews", e);
    }
    return defaultReviews;
}

function handleFirestoreError(error, operationType, path) {
    const authUser = window.auth?.currentUser;
    const errInfo = {
        error: error instanceof Error ? error.message : String(error),
        authInfo: {
            userId: authUser?.uid || null,
            email: authUser?.email || null,
            emailVerified: authUser?.emailVerified || null,
            isAnonymous: authUser?.isAnonymous || null,
            tenantId: authUser?.tenantId || null,
            providerInfo: authUser?.providerData?.map(provider => ({
                providerId: provider.providerId,
                email: provider.email,
            })) || []
        },
        operationType,
        path
    };
    console.error('Firestore Error: ', JSON.stringify(errInfo));
    throw new Error(JSON.stringify(errInfo));
}

export async function addReviewToCloud(db, firebaseOrReview, optionalReview) {
    const review = optionalReview || firebaseOrReview;
    const path = `reviews/${review.id || 'new'}`;
    try {
        const docRef = db.collection("reviews").doc(review.id || `rev-${Date.now()}`);
        const payload = {
            ...review,
            createdAt: review.createdAt || Date.now(),
        };
        await docRef.set(payload, { merge: true });
        return payload;
    } catch (e) {
        console.error("Could not add review to cloud", e);
        handleFirestoreError(e, "write", path);
    }
}

export async function deleteReviewFromCloud(db, reviewId) {
    const path = `reviews/${reviewId}`;
    try {
        await db.collection("reviews").doc(reviewId).delete();
    } catch (e) {
        console.error("Could not delete review from cloud", e);
        handleFirestoreError(e, "delete", path);
    }
}
